#!/usr/bin/env python3
"""Generate per-cell env files for the mismatch study from a declarative spec.

WHY THIS EXISTS. The cells were previously written by hand-rolled heredocs, once per
experiment. That duplicated the whole env body every time, and the duplicates drifted:
one batch ended up with a stale GPU_NODE_ROLE, another with EFA cards hardcoded to 8,
and a third silently produced zero files because a quoting mistake swallowed the
heredoc. A cell is really just "the shared base, plus a few overrides", so express it
that way and generate the files.

A spec is JSON:

  {
    "base": "env_common",              # sourced first by every cell
    "prefix": "env_p1v_",              # filename prefix for generated cells
    "common": {                        # applied to every cell (values are literals)
      "LEARNING_RATE": "\\"1e-6\\"",
      "NUM_ROLLOUT": "1"
    },
    "common_extra_args": "--use-tensorboard --get-mismatch-metrics ...",
    "checkpoint_root": "/fsx/runs",    # CHECKPOINT_DIR/TENSORBOARD_DIR are derived
    "tensorboard_root": "/fsx/tb",
    "cells": [
      {"name": "tp1_s42", "vars": {"TP_SIZE": "1"}, "extra_args": "--seed 42"},
      ...
    ]
  }

Nothing about a GPU type, cluster or namespace appears here: those live in the base env
file that each generated cell sources. Paths come from the spec, not from constants.

Usage:
  python3 gen_cells.py spec.json --outdir /path/to/out [--dry-run]
"""

import argparse
import hashlib
import json
import os
import re
import shlex
import sys


HEADER = """# GENERATED by lib/gen_cells.py from {spec_name} (sha256:{spec_sha}) -- do not edit.
# Cell: {cell_name}
{note}"""


# --- the weight sync study's placement axis ----------------------------------------
#
# This study compares two PLACEMENTS of the trainer and the rollout engines. That choice
# is not one env var: it fixes which implementation class miles instantiates
# (megatron_utils/actor.py:217-221), how ROLLOUT_NUM_GPUS is interpreted, and how much HBM
# an engine may take. Spelling those out per cell is how the study ended up with an arm
# that could not run at all: the 4B recipe hardcoded `--colocate` while still echoing
# ${COLOCATE}, so every "disaggregated" cell silently measured the colocated path, and
# H200 had no disaggregated numbers for the whole study until this was found.
#
# So make the placement itself the field a cell sets, and derive the rest here, once.
#
#   colocated      trainer and engines time-share the SAME devices. ROLLOUT_NUM_GPUS is
#                  the count they share, so it must equal the actor GPU count. Transfer
#                  is CUDA IPC (UpdateWeightFromTensor).
#   disaggregated  engines get their OWN devices. ROLLOUT_NUM_GPUS is a SEPARATE pool, so
#                  actor + rollout must both fit the cluster. Transfer is an NCCL
#                  broadcast (UpdateWeightFromDistributed), over EFA when the pools land
#                  on different nodes.
#
# Deliberately NOT derived: SGLANG_MEM_FRACTION. Colocated must leave room for the trainer
# on the same device and disaggregated need not, so the natural values differ -- but that
# difference lands inside the very quantity being compared, because only the colocated path
# calls pause_generation + flush_cache on every sync (update_weight_from_tensor.py:213-215).
# Deriving it would bake that confound into the harness and make "same mem-fraction, both
# placements" impossible to express. Cells set it explicitly, and `comparisons` (below) is
# what checks that a pair meant to differ only in placement actually does.
SYNC_METHODS = ("colocated", "disaggregated")

# Layout variables a placement-bearing cell must state. Leaving one out is a spec bug, not
# a default to be guessed: a missing ROLLOUT_NUM_GPUS would silently skip the very check
# that distinguishes the two placements.
REQUIRED_LAYOUT_VARS = (
    "ACTOR_NUM_NODES",
    "ACTOR_GPUS_PER_NODE",
    "ROLLOUT_NUM_GPUS",
    "CLUSTER_GPUS",
)


def _require_int(vars_, key, cell_name):
    """Read an integer, distinguishing "absent" from "present but not a number".

    The bug this study is recovering from was a check that quietly did nothing. A helper
    that swallows both KeyError and ValueError into None reproduces exactly that: a typo
    like ACTOR_NUM_NODEZ would disable the layout checks without a word. So absence is the
    caller's decision to make, and a malformed value is always fatal.
    """
    if key not in vars_:
        return None
    raw = str(vars_[key])
    try:
        return int(raw)
    except ValueError:
        raise ValueError(
            f"cell {cell_name}: {key}={raw!r} is not an integer"
        ) from None


def _expand_sync_method(merged, cell_name):
    """Turn SYNC_METHOD into the vars the recipe reads, and reject impossible layouts.

    Returns a new dict. SYNC_METHOD is kept in the output: the generated env file is the
    audit trail, and a reader should not have to infer the placement from COLOCATE.
    """
    method = merged.get("SYNC_METHOD")
    if method is None:
        return merged  # cells outside this study are unaffected
    if method not in SYNC_METHODS:
        raise ValueError(
            f"cell {cell_name}: SYNC_METHOD must be one of {SYNC_METHODS}, got {method!r}"
        )

    out = dict(merged)
    derived = "true" if method == "colocated" else "false"
    # A cell that sets both SYNC_METHOD and COLOCATE has two sources of truth. Silently
    # letting one win is the shape of the original bug (COLOCATE set, ignored). Agreement
    # is redundant but harmless; disagreement is a spec error.
    stated = out.get("COLOCATE")
    if stated is not None and str(stated).lower() != derived:
        raise ValueError(
            f"cell {cell_name}: SYNC_METHOD={method} implies COLOCATE={derived}, but the "
            f"cell also sets COLOCATE={stated!r}. Drop the COLOCATE line; SYNC_METHOD owns it."
        )
    out["COLOCATE"] = derived

    missing = [k for k in REQUIRED_LAYOUT_VARS if k not in out]
    if missing:
        raise ValueError(
            f"cell {cell_name}: SYNC_METHOD={method} requires {', '.join(missing)}. "
            "A layout check that cannot run is worse than no check: it reads as a pass."
        )

    nodes = _require_int(out, "ACTOR_NUM_NODES", cell_name)
    per_node = _require_int(out, "ACTOR_GPUS_PER_NODE", cell_name)
    rollout_gpus = _require_int(out, "ROLLOUT_NUM_GPUS", cell_name)
    cap = _require_int(out, "CLUSTER_GPUS", cell_name)
    actor_gpus = nodes * per_node

    # Holds for both placements: the trainer alone cannot exceed the cluster.
    if actor_gpus > cap:
        raise ValueError(
            f"cell {cell_name}: actor needs {nodes}x{per_node}={actor_gpus} GPUs, "
            f"more than CLUSTER_GPUS={cap}"
        )

    if method == "colocated":
        if rollout_gpus != actor_gpus:
            raise ValueError(
                f"cell {cell_name}: colocated shares devices, so ROLLOUT_NUM_GPUS "
                f"({rollout_gpus}) must equal the actor GPU count ({actor_gpus})"
            )
    else:
        total = actor_gpus + rollout_gpus
        if total > cap:
            raise ValueError(
                f"cell {cell_name}: disaggregated needs actor {actor_gpus} + rollout "
                f"{rollout_gpus} = {total} GPUs, more than CLUSTER_GPUS={cap}. Ray would "
                "wait forever on an unschedulable placement group rather than fail."
            )

    per_engine = _require_int(out, "ROLLOUT_GPUS_PER_ENGINE", cell_name)
    if per_engine is not None:
        if per_engine <= 0 or rollout_gpus % per_engine != 0:
            raise ValueError(
                f"cell {cell_name}: ROLLOUT_GPUS_PER_ENGINE ({per_engine}) must be a "
                f"positive divisor of ROLLOUT_NUM_GPUS ({rollout_gpus})"
            )
    return out


def _cell_vars(spec, cell):
    """The effective variables of one cell, after SYNC_METHOD expansion."""
    merged = dict(spec.get("common") or {})
    merged.update(cell.get("vars") or {})
    return _expand_sync_method(merged, cell["name"])


def check_comparisons(spec):
    """Verify the pairs the spec claims to compare really differ in only what it says.

    A cell-by-cell check cannot catch the mistake that actually happened here: the first
    disaggregated measurement ran at mem-fraction 0.85 against a colocated arm at 0.8, so
    the reported "method difference" also contained a mem-fraction difference. Each cell
    was individually valid. The experiment was not.

    So let the spec state its comparisons, and check them:

        "comparisons": [
          {"cells": ["colo_tp1_mf08", "disagg_tp1_mf08"],
           "must_differ": ["SYNC_METHOD"],
           "must_match": ["SGLANG_MEM_FRACTION", "TP_SIZE", "NUM_ROLLOUT"]}
        ]

    must_match keys are also required to be PRESENT in both cells: comparing two cells
    that both omit a variable proves nothing about the variable.
    """
    comparisons = spec.get("comparisons") or []
    if not comparisons:
        return []

    by_name = {}
    for cell in spec["cells"]:
        by_name[cell["name"]] = _cell_vars(spec, cell)

    problems = []
    for i, cmp_ in enumerate(comparisons):
        label = cmp_.get("label") or f"comparisons[{i}]"
        names = cmp_.get("cells") or []
        if len(names) < 2:
            problems.append(f"{label}: needs at least 2 cells, got {names}")
            continue
        unknown = [n for n in names if n not in by_name]
        if unknown:
            problems.append(f"{label}: unknown cell(s) {unknown}")
            continue

        for key in cmp_.get("must_match") or []:
            present = [n for n in names if key in by_name[n]]
            if len(present) != len(names):
                absent = [n for n in names if n not in present]
                problems.append(
                    f"{label}: must_match {key} is absent from {absent}; two cells that "
                    "both omit a variable do not agree on it, they are both silent"
                )
                continue
            values = {n: str(by_name[n][key]) for n in names}
            if len(set(values.values())) > 1:
                problems.append(f"{label}: must_match {key} differs: {values}")

        for key in cmp_.get("must_differ") or []:
            values = {n: str(by_name[n].get(key)) for n in names}
            if len(set(values.values())) != len(names):
                problems.append(
                    f"{label}: must_differ {key} is not distinct across cells: {values}"
                )
    return problems


def render_cell(spec, cell, spec_name, spec_sha="unknown", base_source=None):
    """Return the text of one env file.

    base_source is the path the cell will `source`. It should be the FROZEN copy written
    next to the generated cells, not the spec's base_path: sourcing the original leaves the
    run depending on a file under /tmp that can be edited or reclaimed between generation
    and execution, so the frozen copy would be an audit trail of a file nobody read.
    """
    name = cell["name"]
    # The name becomes part of a filename, a checkpoint path and a results.tsv key, so a
    # slash or a space in it nests artefacts somewhere unintended -- the same class of
    # accident the driver's EXP_NAME guard exists for.
    if not re.fullmatch(r"[A-Za-z0-9._-]+", name):
        raise ValueError(f"cell name must be a plain token: {name!r}")
    note_lines = []
    for line in (cell.get("note") or spec.get("note") or "").strip().splitlines():
        note_lines.append(f"# {line}" if line.strip() else "#")
    note = "\n".join(note_lines)

    out = [HEADER.format(spec_name=spec_name, spec_sha=spec_sha,
                         cell_name=name, note=note).rstrip(), ""]
    out.append(f"source {shlex.quote(base_source or spec['base_path'])}")

    # One place computes a cell's effective variables, so the file that gets written and
    # the values check_comparisons() reasons about can never drift apart.
    merged = _cell_vars(spec, cell)
    for k, v in merged.items():
        # Quote every value. Unquoted values break on whitespace, ';' and '$', and an
        # unquoted heredoc is what silently produced a zero-cell batch once already.
        # JSON booleans would otherwise reach the shell as Python's True/False.
        if isinstance(v, bool):
            v = "true" if v else "false"
        out.append(f"export {k}={shlex.quote(str(v))}")

    # Derived output paths: keep every cell's artefacts separate without the spec
    # having to spell each one out.
    tag = f"{spec.get('tag_prefix', '')}{name}"
    if spec.get("checkpoint_root"):
        out.append("export CHECKPOINT_DIR="
                   + shlex.quote(f"{spec['checkpoint_root']}/{tag}/ckpt"))
    if spec.get("tensorboard_root"):
        out.append("export TENSORBOARD_DIR="
                   + shlex.quote(f"{spec['tensorboard_root']}/{tag}"))
    if spec.get("dump_root"):
        # Per-token dump destination for the position-profile analysis. Tag it so a
        # batch's dumps do not collide.
        out.append("export MIS_DUMP_DIR="
                   + shlex.quote(f"{spec['dump_root']}/{tag}"))
        out.append("export MIS_DUMP_TAG=" + shlex.quote(tag))

    extra = " ".join(
        x for x in [spec.get("common_extra_args", ""), cell.get("extra_args", "")] if x
    ).strip()
    if extra:
        out.append("export EXTRA_TRAIN_ARGS=" + shlex.quote(extra))

    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    with open(a.spec, "rb") as f:
        raw = f.read()
    spec_sha = hashlib.sha256(raw).hexdigest()[:12]
    spec = json.loads(raw)
    if "base_path" not in spec:
        print("spec must define base_path (the env file every cell sources)", file=sys.stderr)
        return 2

    spec_name = os.path.basename(a.spec)

    # Check the comparisons BEFORE writing anything. A spec whose two arms differ in more
    # than it claims produces cells that each look fine and an experiment that cannot be
    # attributed; generating them anyway just moves the discovery to after the GPU hours
    # are spent. Refuse instead, and say which key differs.
    problems = check_comparisons(spec)
    if problems:
        print(f"{spec_name}: the declared comparisons do not hold:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 2

    if not a.dry_run:
        os.makedirs(a.outdir, exist_ok=True)

    # Freeze the base env's contents, not just its path. Cells only `source` the base, so
    # a base living under /tmp (which is what gets reclaimed) leaves the model paths,
    # dataset and topology unrecoverable once the cluster is gone -- the very failure the
    # driver was rewritten to prevent. Copy it next to the generated cells and record its
    # hash so a later audit can tell which base a result came from.
    # The generated cells source the FROZEN copy, not spec["base_path"]. Freezing a copy
    # while the cells still sourced the original made the frozen file an audit trail of
    # something nobody read: the base could be edited (or reclaimed, it lives under /tmp)
    # between generation and submission, and the recorded hash would then describe a file
    # that never ran.
    base = spec["base_path"]
    base_source = None
    if not a.dry_run:
        if os.path.isfile(base):
            raw_base = open(base, "rb").read()
            base_sha = hashlib.sha256(raw_base).hexdigest()[:12]
            frozen = os.path.join(a.outdir, f"base.{base_sha}.env")
            with open(frozen, "wb") as f:
                f.write(raw_base)
            base_source = os.path.abspath(frozen)
            print(f"froze base env {base} -> {frozen} (cells source the frozen copy)")
        else:
            # Without a readable base there is nothing to freeze, and falling back to
            # sourcing a path that does not exist would fail at run time with a confusing
            # error. Refuse instead: a batch that cannot be reproduced should not be
            # generated silently.
            print(f"ERROR: base_path {base} is not readable, so it cannot be frozen and "
                  "the cells would not be reproducible.", file=sys.stderr)
            return 2

    names = [c["name"] for c in spec["cells"]]
    if len(names) != len(set(names)):
        dupes = sorted({n for n in names if names.count(n) > 1})
        print(f"duplicate cell names: {dupes}", file=sys.stderr)
        return 2

    for cell in spec["cells"]:
        text = render_cell(spec, cell, spec_name, spec_sha, base_source)
        path = os.path.join(a.outdir, f"{spec.get('prefix', 'env_')}{cell['name']}")
        if a.dry_run:
            print(f"--- {path}")
            print(text)
        else:
            with open(path, "w") as f:
                f.write(text)
    print(f"{len(spec['cells'])} cells -> {a.outdir}" if not a.dry_run
          else f"{len(spec['cells'])} cells (dry run)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
